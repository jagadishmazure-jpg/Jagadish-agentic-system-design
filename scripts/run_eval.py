"""Run the full evaluation and learning loop on the synthetic suite; write results/.

    python scripts/run_eval.py          # rewrite results/metrics.json, results/eval_report.md, data/regression_set.json
    python scripts/run_eval.py --check  # recompute and fail if any committed result differs (CI)

Every number in README.md and docs/ that carries a marker comes from results/metrics.json.
All scenarios, passengers and airlines are synthetic; latency and cost are simulated.
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from harrowgate.knowledge import FaqRetriever, choose_store  # noqa: E402
from harrowgate.learning import learning_loop  # noqa: E402
from harrowgate.requirements import SPEC, validate_spec  # noqa: E402
from harrowgate.scenarios import FAQ_SET, STORE_SET, build_suite  # noqa: E402
from harrowgate.tools import REGISTRY  # noqa: E402


def compute() -> tuple[dict, list[str], str]:
    suite = build_suite()
    report = learning_loop(suite)
    first = report.rounds[0]
    from harrowgate.evaluation import run_suite
    from harrowgate.system import BASELINE
    v0 = run_suite(suite, BASELINE).summary()
    final = report.final.summary()
    store_hits = sum(choose_store(q)[0] == e for q, e in STORE_SET)
    retr = FaqRetriever()
    faq_hits = sum(retr.search(q, 1)[0]["id"] == e for q, e in FAQ_SET)
    metrics = {
        "label": "synthetic scenarios on a simulated airport; latency and cost are simulated",
        "suite": {"scenarios": len(suite), "families": len(Counter(s["family"] for s in suite))},
        "spec_problems": len(validate_spec(SPEC, set(REGISTRY))),
        "learning": [{"version": r.version, "cause": r.cause, "change": r.change, "success": r.success,
                      "passed": r.passed, "released": r.released, "regressions": r.regressions,
                      "causes": r.causes} for r in report.rounds],
        "v0": v0,
        "final": final,
        "improvement_points": round((final["success"]["rate"] - v0["success"]["rate"]) * 100, 1),
        "knowledge": {"store_choice": {"n": len(STORE_SET), "correct": store_hits,
                                       "rate": round(store_hits / len(STORE_SET), 4)},
                      "faq_hit_at_1": {"n": len(FAQ_SET), "correct": faq_hits,
                                       "rate": round(faq_hits / len(FAQ_SET), 4)}},
        "known_misses": report.known_misses,
        "open_causes": report.open_causes,
        "regression_set_size": len(report.regression_set),
        "first_round_success": first.success,
    }
    return metrics, report.regression_set, render_report(metrics)


def render_report(m: dict) -> str:
    v0, f = m["v0"], m["final"]
    lines = [
        "# Evaluation report",
        "",
        "Generated by `python scripts/run_eval.py`. **Synthetic** scenarios on a **simulated** airport; latency is the",
        "sum of declared per-tool latencies and cost uses an assumed token price, so both are **simulated**.",
        f"Suite: {m['suite']['scenarios']} scenarios in {m['suite']['families']} families. This is a self-written "
        "regression suite, not a benchmark.",
        "",
        "## Learning loop",
        "",
        "| Version | Failure pattern fixed | Change | Success | Passed | Released | Regressions |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in m["learning"]:
        lines.append(f"| {r['version']} | {r['cause'] or '-'} | {r['change'] or 'baseline'} | {r['success'] * 100:.1f}% | "
                     f"{r['passed']}/{m['suite']['scenarios']} | {'yes' if r['released'] else 'no'} | "
                     f"{len(r['regressions'])} |")
    lines += ["", "## v0 vs final, per check", "", "| Check | v0 | final |", "| --- | --- | --- |"]
    for c in f["checks"]:
        lines.append(f"| {c} | {v0['checks'][c] * 100:.1f}% | {f['checks'][c] * 100:.1f}% |")
    lines += [
        "", "## Process and cost (final version)", "",
        "| Metric | v0 | final |", "| --- | --- | --- |",
        f"| success (Wilson 95% CI) | {v0['success']['rate'] * 100:.1f}% ({v0['success']['wilson95'][0] * 100:.1f}-"
        f"{v0['success']['wilson95'][1] * 100:.1f}) | {f['success']['rate'] * 100:.1f}% "
        f"({f['success']['wilson95'][0] * 100:.1f}-{f['success']['wilson95'][1] * 100:.1f}) |",
        f"| duplicate side effects | {v0['duplicate_effects']} | {f['duplicate_effects']} |",
        f"| unauthorized actions | {v0['unauthorized_actions']} | {f['unauthorized_actions']} |",
        f"| repeated reads (all / excluding bag-scan polling) | {v0['duplicate_reads']} / "
        f"{v0['duplicate_reads_not_polling']} | {f['duplicate_reads']} / {f['duplicate_reads_not_polling']} |",
        f"| avg tool calls per request | {v0['avg_tool_calls']} | {f['avg_tool_calls']} |",
        f"| avg model tokens per request | {v0['avg_tokens']} | {f['avg_tokens']} |",
        f"| simulated latency p50 / p95 (ms) | {v0['sim_latency_ms']['p50']} / {v0['sim_latency_ms']['p95']} | "
        f"{f['sim_latency_ms']['p50']} / {f['sim_latency_ms']['p95']} |",
        f"| simulated cost per request (USD, assumed price) | {v0['sim_cost_usd_per_request']} | "
        f"{f['sim_cost_usd_per_request']} |",
        f"| escalation rate | {v0['escalation_rate'] * 100:.1f}% | {f['escalation_rate'] * 100:.1f}% |",
        f"| context packet vs everything (tokens) | {v0['context']['avg_packet_tokens']} vs "
        f"{v0['context']['avg_raw_tokens']} | {f['context']['avg_packet_tokens']} vs {f['context']['avg_raw_tokens']} |",
        "", "## Families (final)", "", "| Family | Passed |", "| --- | --- |",
    ]
    for fam, v in f["families"].items():
        lines.append(f"| {fam} | {v['passed']}/{v['n']} |")
    k = m["knowledge"]
    lines += ["", "## Knowledge layer checks", "",
              f"- Store choice (graph / database / retrieval): {k['store_choice']['correct']}/{k['store_choice']['n']}",
              f"- FAQ retrieval hit@1: {k['faq_hit_at_1']['correct']}/{k['faq_hit_at_1']['n']}",
              "", "## Known misses (kept as failing scenarios on purpose)", ""]
    for sid, why in m["known_misses"].items():
        lines.append(f"- `{sid}`: {why}")
    return "\n".join(lines) + "\n"


def main() -> int:
    metrics, regression, report = compute()
    outs = {ROOT / "results/metrics.json": json.dumps(metrics, indent=2, sort_keys=True) + "\n",
            ROOT / "data/regression_set.json": json.dumps({"description": "scenario ids that must keep passing",
                                                           "ids": regression}, indent=2) + "\n",
            ROOT / "results/eval_report.md": report}
    if "--check" in sys.argv:
        bad = [str(p.relative_to(ROOT)) for p, text in outs.items() if not p.exists() or p.read_text() != text]
        if bad:
            print("results differ from a fresh run:", ", ".join(bad))
            return 1
        print(f"results match a fresh run ({metrics['suite']['scenarios']} scenarios, final success "
              f"{metrics['final']['success']['rate'] * 100:.1f}%).")
        return 0
    for p, text in outs.items():
        p.parent.mkdir(exist_ok=True)
        p.write_text(text)
    print(f"wrote results ({metrics['suite']['scenarios']} scenarios, v0 {metrics['v0']['success']['rate'] * 100:.1f}% "
          f"-> final {metrics['final']['success']['rate'] * 100:.1f}%)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
